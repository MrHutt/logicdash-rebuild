// @ts-check
import { defineConfig } from 'astro/config';
import sitemap from '@astrojs/sitemap';
import { readFile, writeFile } from 'node:fs/promises';
import { execSync } from 'node:child_process';
import { existsSync } from 'node:fs';

function lessonCodeRedirects() {
	return {
		name: 'lesson-code-redirects',
		hooks: {
			'astro:build:done': async (/** @type {{ dir: URL, logger: any }} */ { dir, logger }) => {
				const codes = JSON.parse(await readFile(new URL('lesson-codes.json', dir), 'utf8'));
				const byTarget = new Map();
				for (const [code, href] of Object.entries(codes)) {
					if (!/^[0-9A-Z]{3}$/.test(code)) throw new Error(`Unexpected lesson code ${code}`);
					byTarget.set(href, [...(byTarget.get(href) ?? []), code]);
				}
				const rules = [...byTarget]
					.map(([href, list]) => `RewriteRule ^(${list.join('|')})/?$ ${href}/ [NC,R=302,L]`)
					.join('\n');
				const block = `# BEGIN LogicDash lesson codes (generated by the build)
<IfModule mod_rewrite.c>
RewriteEngine On
${rules}
</IfModule>
ErrorDocument 404 /404.html
# END LogicDash lesson codes
`;
				await writeFile(new URL('.htaccess', dir), block);
				await writeFile(new URL('htaccess-lesson-codes.txt', dir), block);
				logger.info(`.htaccess written with ${Object.keys(codes).length} lesson codes`);
			},
		},
	};
}

/** @param {string} file */
function gitDate(file) {
	try {
		return execSync(`git log -1 --format=%cs -- "${file}"`, { encoding: 'utf8' }).trim();
	} catch {
		return '';
	}
}

const FALLBACK_DATE = '2026-11-14';

/** @param {string} url */
function lastmodFor(url) {
	const path = new URL(url).pathname.replace(/^\/|\/$/g, '');
	const candidates = path
		? [`src/pages/${path}.astro`, `src/pages/${path}/index.astro`, `src/pages/${path}.md`]
		: ['src/pages/index.astro'];
	for (const file of candidates) {
		if (existsSync(file)) return gitDate(file) || FALLBACK_DATE;
	}
	return FALLBACK_DATE;
}

// https://astro.build/config
export default defineConfig({
	site: 'https://logicdash.io',
	integrations: [
		sitemap({
			filter: (page) => !/^https:\/\/logicdash\.io\/([0-9a-f]{3}|404)\/?$/i.test(page),
			serialize: (item) => ({
				...item,
				lastmod: lastmodFor(item.url),
			}),
		}),
		lessonCodeRedirects(),
	],
});