// @ts-check
import { defineConfig } from 'astro/config';
import sitemap from '@astrojs/sitemap';
import { readFile, writeFile } from 'node:fs/promises';

/**
 * Writes dist/.htaccess for the Apache server on SiteGround: lesson short
 * links (/5A2, /5a2, /5a2/) redirect to their lesson whatever the letter
 * case. Only the known codes from dist/lesson-codes.json are matched, so no
 * other URL is touched. The query string is kept (Apache passes it along by
 * default). 302 rather than 301, so a code can be re-pointed later without
 * browsers having cached the old target. The 404 page is also registered,
 * so any mistyped code still gets a helpful page.
 * @returns {import('astro').AstroIntegration}
 */
function lessonCodeRedirects() {
	return {
		name: 'lesson-code-redirects',
		hooks: {
			'astro:build:done': async ({ dir, logger }) => {
				const codes = JSON.parse(await readFile(new URL('lesson-codes.json', dir), 'utf8'));
				const byTarget = new Map();
				for (const [code, href] of Object.entries(codes)) {
					if (!/^[0-9A-Z]{3}$/.test(code)) throw new Error(`Unexpected lesson code ${code}`);
					byTarget.set(href, [...(byTarget.get(href) ?? []), code]);
				}
				const rules = [...byTarget]
					.map(([href, list]) => `RewriteRule ^(${list.join('|')})/?$ ${href}/ [NC,R=302,L]`)
					.join('\n');
				const block = `# BEGIN LogicDash lesson codes (generated by the build; see docs/pseudocode-practice-audit.md)
<IfModule mod_rewrite.c>
RewriteEngine On
${rules}
</IfModule>
ErrorDocument 404 /404.html
# END LogicDash lesson codes
`;
				await writeFile(new URL('.htaccess', dir), block);
				await writeFile(new URL('htaccess-lesson-codes.txt', dir), block);
				logger.info(`.htaccess written with ${Object.keys(codes).length} lesson codes`);
			},
		},
	};
}

// https://astro.build/config
export default defineConfig({
	site: 'https://logicdash.io',
	integrations: [
		// Every page is public and indexable, including all /tools/ pages.
		// Short-link redirects (/5A2, see src/pages/[code].astro) and the
		// 404 page are left out.
		sitemap({ filter: (page) => !/^https:\/\/logicdash\.io\/([0-9a-f]{3}|404)\/?$/i.test(page) }),
		lessonCodeRedirects(),
	],
});
